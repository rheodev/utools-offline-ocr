export const messages = { 'zh-CN': zh, en }

export function translate(locale: Locale, message: LocalizedMessage): string {
  return messages[locale][message.key].replace(/\{(\w+)\}/g, (placeholder, key: string) =>
    String(message.params?.[key] ?? placeholder))
}

export function errorMessage(error: unknown, fallback: MessageKey = 'error.operation'): LocalizedMessage {
  const key = error && typeof error === 'object' && 'message' in error && typeof error.message === 'string'
    ? error.message : ''
  return { key: Object.hasOwn(zh, key) ? key as MessageKey : fallback }
}
